#!/usr/bin/env python3
"""Builds Brasa's Kvantum theme (flat, rounded, night blue and red) for Qt apps from Kvantum's own
KvLibadwaitaMaiaDark, which looks like libadwaita, so Qt and GTK apps match.
Usage: docs/gen-kvantum.py [source dir] [output dir]
  defaults: /usr/share/Kvantum/KvLibadwaitaMaia  config/kvantum/Brasa
The result is derived from Kvantum's themes (GPL-3.0, https://github.com/tsujan/Kvantum)."""
import os, re, sys

HERE = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/Kvantum/KvLibadwaitaMaia"
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "config/kvantum/Brasa")

# Greys become Brasa's blues by brightness (gray level -> color), linearly between these points
RAMP = [(0, "#000000"), (30, "#000208"), (44, "#00040f"), (60, "#08122b"), (69, "#0c1838"), (77, "#132450"),
        (86, "#1c2f5e"), (97, "#2c3a5e"), (110, "#3a4a74"), (152, "#5a6a90"), (193, "#8f9cc0"),
        (223, "#c3cbe0"), (239, "#e6eaf5"), (255, "#ffffff")]
# The teal accent and a few others become Brasa's reds
ACCENT = {"#16a085": "#c00000", "#159f7f": "#b00000", "#19b391": "#ff3030", "#3f776c": "#7a0000",
          "#a6d9cc": "#ff9999", "#21e0b6": "#ff3030", "#70c2ad": "#ff7a7a", "#16a585": "#c00000",
          "#b74aff": "#ff7a3d", "#f04a50": "#ff0000", "#31363b": "#0c1838", "#acb1bc": "#8f9cc0",
          "#f2ffff": "#ffffff", "#0057ae": "#ff3030", "#e040fb": "#ff7a3d"}
GENERAL = {"window.color": "#00040f", "base.color": "#040b1f", "alt.base.color": "#08122b",
           "button.color": "#0c1838", "light.color": "#2c3a5e", "mid.light.color": "#1a2848",
           "dark.color": "#000208", "mid.color": "#08122b", "highlight.color": "#c00000",
           "inactive.highlight.color": "#7a0000", "text.color": "#ffffff", "window.text.color": "#ffffff",
           "button.text.color": "#ffffff", "disabled.text.color": "#5a6a90", "tooltip.text.color": "#ffffff",
           "highlight.text.color": "#ffffff", "link.color": "#ff3030", "link.visited.color": "#ff7a3d",
           "progress.indicator.text.color": "#ffffff"}


def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def ramp(level):
    for (a, ca), (b, cb) in zip(RAMP, RAMP[1:]):
        if a <= level <= b:
            t = (level - a) / (b - a) if b > a else 0
            return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(rgb(ca), rgb(cb)))
    return "#ffffff"


def recolor(m):
    h, alpha = m.group(1).lower(), m.group(2) or ""   # #RRGGBB, optionally followed by AA
    if h in ACCENT: return ACCENT[h] + alpha
    r, g, b = rgb(h)
    if max(r, g, b) - min(r, g, b) <= 12:          # a grey (or nearly)
        return ramp(round((r + g + b) / 3)) + alpha
    return h + alpha


os.makedirs(out, exist_ok=True)
hexcol = re.compile(r"(#[0-9a-fA-F]{6})([0-9a-fA-F]{2})?\b")
svg = hexcol.sub(recolor, open(os.path.join(src, "KvLibadwaitaMaiaDark.svg"), encoding="utf-8").read())
open(os.path.join(out, "Brasa.svg"), "w", encoding="utf-8").write(svg)
kv = hexcol.sub(recolor, open(os.path.join(src, "KvLibadwaitaMaiaDark.kvconfig"), encoding="utf-8").read())
kv = re.sub(r"(?m)^text\.disabled\.color=.*$", "text.disabled.color=#5a6a90", kv)   # readable when disabled
for k, v in GENERAL.items():
    kv = re.sub(rf"(?m)^{re.escape(k)}=.*$", f"{k}={v}", kv)
kv = "# Brasa · Redline for Kvantum, generated by docs/gen-kvantum.py from KvLibadwaitaMaiaDark (GPL-3.0)\n" + kv
open(os.path.join(out, "Brasa.kvconfig"), "w", encoding="utf-8").write(kv)
print("kvantum: Brasa theme written to", out)
